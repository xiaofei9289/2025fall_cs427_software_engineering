package edu.uiuc.cs427app.ui.fragment;

import android.graphics.Color;
import android.os.Bundle;
import android.util.Log;
import android.view.Gravity;
import android.view.LayoutInflater;
import android.view.View;
import android.view.ViewGroup;
import android.widget.Button;
import android.widget.LinearLayout;
import android.widget.ProgressBar;
import android.widget.TextView;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.fragment.app.Fragment;
import androidx.lifecycle.ViewModelProvider;

import com.google.gson.Gson;

import java.util.List;

import edu.uiuc.cs427app.MainActivity;
import edu.uiuc.cs427app.R;
import edu.uiuc.cs427app.data.entity.Theme;
import edu.uiuc.cs427app.data.entity.WeatherData;
import edu.uiuc.cs427app.helper.LLMHelper;
import edu.uiuc.cs427app.network.model.WeatherInsightsResponse;
import edu.uiuc.cs427app.viewmodel.ThemeViewModel;

/**
 * WeatherInsightFragment - Displays LLM-generated weather insights.
 *
 * This fragment shows AI-generated questions about the weather and provides
 * answers when users click on the questions.
 *
 * Requirements (Iteration 4):
 * - Display at least 2 context-relevant questions generated by LLM
 * - Questions must be presented as clickable buttons
 * - When clicked, generate and display LLM answer
 * - No hardcoded questions or answers (all dynamically generated)
 *
 * @author CS427 Team 407
 */
public class WeatherInsightFragment extends Fragment {

    private static final String TAG = "WeatherInsightFragment";
    private static final String ARG_CITY_NAME = "cityName";
    private static final String ARG_TEMPERATURE = "temperature";
    private static final String ARG_CONDITIONS = "conditions";
    private static final String ARG_HUMIDITY = "humidity";
    private static final String ARG_WIND_SPEED = "windSpeed";

    private TextView tvTitle;
    private TextView tvInstructions;
    private ProgressBar progressBar;
    private LinearLayout questionsContainer;
    private LinearLayout answerSection;
    private TextView tvAnswer;
    private TextView tvError;
    private Button btnBack;

    private ThemeViewModel themeViewModel;
    private LLMHelper llmHelper;
    private Gson gson;

    private String cityName;
    private WeatherData weatherData;

    /**
     * Factory method to create WeatherInsightFragment with weather data.
     *
     * @param cityName    Name of the city
     * @param weatherData Weather data for insights generation
     * @return New instance of WeatherInsightFragment
     */
    public static WeatherInsightFragment newInstance(String cityName, WeatherData weatherData) {
        WeatherInsightFragment fragment = new WeatherInsightFragment();
        Bundle args = new Bundle();
        args.putString(ARG_CITY_NAME, cityName);
        args.putDouble(ARG_TEMPERATURE, weatherData.getTemperature());
        args.putString(ARG_CONDITIONS, weatherData.getConditions());
        args.putInt(ARG_HUMIDITY, weatherData.getHumidity());
        args.putDouble(ARG_WIND_SPEED, weatherData.getWindSpeed());
        fragment.setArguments(args);
        return fragment;
    }

    @Override
    public void onCreate(@Nullable Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        // Initialize helpers
        llmHelper = new LLMHelper();
        gson = new Gson();

        // Get arguments
        if (getArguments() != null) {
            cityName = getArguments().getString(ARG_CITY_NAME, "Unknown");

            // Reconstruct WeatherData from arguments
            weatherData = new WeatherData();
            weatherData.setTemperature(getArguments().getDouble(ARG_TEMPERATURE, 0.0));
            weatherData.setConditions(getArguments().getString(ARG_CONDITIONS, "Unknown"));
            weatherData.setHumidity(getArguments().getInt(ARG_HUMIDITY, 0));
            weatherData.setWindSpeed(getArguments().getDouble(ARG_WIND_SPEED, 0.0));
        } else {
            Log.e(TAG, "No arguments provided to WeatherInsightFragment");
            cityName = "Unknown";
            weatherData = new WeatherData(); // Empty data
        }
    }

    @Nullable
    @Override
    public View onCreateView(@NonNull LayoutInflater inflater, @Nullable ViewGroup container,
                             @Nullable Bundle savedInstanceState) {
        View view = inflater.inflate(R.layout.fragment_weather_insights, container, false);

        // Initialize views
        tvTitle = view.findViewById(R.id.tvTitle);
        tvInstructions = view.findViewById(R.id.tvInstructions);
        progressBar = view.findViewById(R.id.progressBar);
        questionsContainer = view.findViewById(R.id.questionsContainer);
        answerSection = view.findViewById(R.id.answerSection);
        tvAnswer = view.findViewById(R.id.tvAnswer);
        tvError = view.findViewById(R.id.tvError);
        btnBack = view.findViewById(R.id.btnBack);

        // Initialize ThemeViewModel
        themeViewModel = new ViewModelProvider(requireActivity()).get(ThemeViewModel.class);

        // Set title
        tvTitle.setText("Weather Insights for " + cityName);

        // Setup back button
        btnBack.setOnClickListener(v -> {
            if (getActivity() instanceof MainActivity) {
                ((MainActivity) getActivity()).onBackPressed();
            }
        });

        // Observe theme changes
        themeViewModel.getCurrentTheme().observe(getViewLifecycleOwner(), theme -> {
            if (theme != null) {
                applyThemeColors(theme, view);
            }
        });

        // Generate insights
        generateWeatherInsights();

        return view;
    }

    /**
     * Generate weather insights by calling LLM to get questions.
     */
    private void generateWeatherInsights() {
        Log.d(TAG, "Generating weather insights for " + cityName);

        // Show loading, hide other elements
        progressBar.setVisibility(View.VISIBLE);
        tvInstructions.setVisibility(View.GONE);
        questionsContainer.setVisibility(View.GONE);
        answerSection.setVisibility(View.GONE);
        tvError.setVisibility(View.GONE);

        llmHelper.generateInsights(weatherData, cityName, new LLMHelper.InsightsCallback() {
            @Override
            public void onSuccess(String insights) {
                if (getActivity() != null) {
                    getActivity().runOnUiThread(() -> {
                        try {
                            Log.d(TAG, "Received insights JSON: " + insights);

                            // Parse JSON response to extract questions
                            WeatherInsightsResponse response = gson.fromJson(insights, WeatherInsightsResponse.class);

                            if (response != null && response.isValid()) {
                                displayQuestions(response.getQuestions());
                            } else {
                                Log.e(TAG, "Invalid response: " + (response == null ? "null" : "no questions"));
                                showError("No questions generated. Please try again.");
                            }
                        } catch (com.google.gson.JsonSyntaxException e) {
                            Log.e(TAG, "JSON parsing error: " + e.getMessage(), e);
                            Log.e(TAG, "Invalid JSON received: " + insights);
                            showError("Failed to parse insights. The response was not valid JSON.");
                        } catch (Exception e) {
                            Log.e(TAG, "Unexpected error parsing insights: " + e.getMessage(), e);
                            showError("Failed to parse insights: " + e.getMessage());
                        }
                    });
                }
            }

            @Override
            public void onError(String errorMessage) {
                if (getActivity() != null) {
                    getActivity().runOnUiThread(() -> {
                        Log.e(TAG, "Error generating insights: " + errorMessage);
                        showError("Error generating insights: " + errorMessage);
                    });
                }
            }
        });
    }

    /**
     * Display questions as clickable buttons.
     *
     * @param questions List of questions from LLM
     */
    private void displayQuestions(List<String> questions) {
        Log.d(TAG, "Displaying " + questions.size() + " questions");

        // Hide loading
        progressBar.setVisibility(View.GONE);

        // Show instructions and questions container
        tvInstructions.setVisibility(View.VISIBLE);
        questionsContainer.setVisibility(View.VISIBLE);

        // Clear any existing buttons
        questionsContainer.removeAllViews();

        // Create a button for each question
        for (int i = 0; i < questions.size(); i++) {
            final String question = questions.get(i);

            Button questionButton = new Button(getContext());
            questionButton.setText(question);
            questionButton.setTextAlignment(View.TEXT_ALIGNMENT_TEXT_START);
            questionButton.setGravity(Gravity.START | Gravity.CENTER_VERTICAL);
            questionButton.setPadding(32, 24, 32, 24);
            questionButton.setAllCaps(false); // Preserve question capitalization

            // Set layout params with margins
            LinearLayout.LayoutParams params = new LinearLayout.LayoutParams(
                    LinearLayout.LayoutParams.MATCH_PARENT,
                    LinearLayout.LayoutParams.WRAP_CONTENT
            );
            params.setMargins(0, 0, 0, 16); // Bottom margin
            questionButton.setLayoutParams(params);

            // Set click listener to generate answer
            questionButton.setOnClickListener(v -> generateAnswer(question));

            // Add button to container
            questionsContainer.addView(questionButton);

            Log.d(TAG, "Added button for question " + (i + 1) + ": " + question);
        }
    }

    /**
     * Generate answer for a selected question.
     *
     * @param question The question to answer
     */
    private void generateAnswer(String question) {
        Log.d(TAG, "Generating answer for: " + question);

        // Show loading in answer section
        answerSection.setVisibility(View.VISIBLE);
        tvAnswer.setText("Generating answer...");
        progressBar.setVisibility(View.VISIBLE);
        tvError.setVisibility(View.GONE);

        llmHelper.generateAnswer(weatherData, question, cityName, new LLMHelper.InsightsCallback() {
            @Override
            public void onSuccess(String answer) {
                if (getActivity() != null) {
                    getActivity().runOnUiThread(() -> {
                        progressBar.setVisibility(View.GONE);
                        tvAnswer.setText(answer);
                        Log.d(TAG, "Answer generated successfully");
                    });
                }
            }

            @Override
            public void onError(String errorMessage) {
                if (getActivity() != null) {
                    getActivity().runOnUiThread(() -> {
                        progressBar.setVisibility(View.GONE);
                        tvAnswer.setText("Error: " + errorMessage);
                        Log.e(TAG, "Error generating answer: " + errorMessage);
                    });
                }
            }
        });
    }

    /**
     * Show error message to user.
     *
     * @param message Error message
     */
    private void showError(String message) {
        progressBar.setVisibility(View.GONE);
        tvInstructions.setVisibility(View.GONE);
        questionsContainer.setVisibility(View.GONE);
        answerSection.setVisibility(View.GONE);
        tvError.setVisibility(View.VISIBLE);
        tvError.setText(message);
    }

    /**
     * Apply theme colors to UI elements.
     *
     * @param theme    Theme object with colors
     * @param rootView Root view of the fragment
     */
    private void applyThemeColors(Theme theme, View rootView) {
        if (theme == null || rootView == null) {
            return;
        }

        try {
            // Apply background color
            int backgroundColor = Color.parseColor(theme.getPrimaryColor());
            rootView.setBackgroundColor(backgroundColor);

            // Apply text color
            int textColor = Color.parseColor(theme.getSecondaryColor());
            tvTitle.setTextColor(textColor);
            tvInstructions.setTextColor(textColor);
            tvError.setTextColor(textColor);

        } catch (Exception e) {
            // Ignore color parse errors
            Log.w(TAG, "Failed to parse theme colors: " + e.getMessage());
        }
    }
}
