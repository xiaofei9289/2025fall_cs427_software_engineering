    /**
     * Predefined theme: Light mode
     * @deprecated Hardcoded themes no longer meet requirements and are disabled. Please use LLM to dynamically generate themes.
     */
    @Deprecated
    public static Theme lightTheme() {
        throw new UnsupportedOperationException(
            "Hardcoded themes are disabled. Themes must be dynamically generated by LLM. Please use LLMHelper.generateTheme() to generate 'light' theme."
        );
    }

    /**
     * Predefined theme: Dark mode
     * @deprecated Hardcoded themes no longer meet requirements and are disabled. Please use LLM to dynamically generate themes.
     */
    @Deprecated
    public static Theme darkTheme() {
        throw new UnsupportedOperationException(
            "Hardcoded themes are disabled. Themes must be dynamically generated by LLM. Please use LLMHelper.generateTheme() to generate 'dark' theme."
        );
    }

