    /**
     * Load all available themes.
     *
     * Loads predefined themes and LLM-generated themes for the current user.
     */
    public void loadAvailableThemes() {
        List<Theme> themes = new ArrayList<>();
        
        // NOTE: No longer adding hardcoded predefined themes
        // All themes must be dynamically generated by LLM, hardcoded colors cannot be used
        
        // Load custom LLM-generated themes if user exists
        if (userId != null) {
            User currentUser = userRepository.getUserById(userId);
            if (currentUser != null && currentUser.getThemePreference() != null) {
                String themeDescription = currentUser.getThemePreference();
                
                // If theme is not a predefined one ("light", "dark", "blue"),
                // it's an LLM-generated theme description
                if (!isPredefinedTheme(themeDescription)) {
                    Theme customTheme = parseLLMTheme(themeDescription);
                    if (customTheme != null) {
                        themes.add(customTheme);
                    }
                }
            }
        }
        
        availableThemes.setValue(themes);
    }
    
    /**
     * Check if a theme is a predefined one.
     * 
     * @param themeDescription Theme name or description
     * @return true if predefined, false if LLM-generated
     */
    private boolean isPredefinedTheme(String themeDescription) {
        return "light".equals(themeDescription) || 
               "dark".equals(themeDescription) || 
               "blue".equals(themeDescription);
    }
    
    /**
     * Parse an LLM-generated theme from its description/JSON.
     * 
     * @param themeDescription Theme description or JSON
     * @return Parsed Theme object
     */
    private Theme parseLLMTheme(String themeDescription) {
        // Try to parse as JSON first
        try {
            int jsonStart = themeDescription.indexOf("{");
            int jsonEnd = themeDescription.lastIndexOf("}");
            
            if (jsonStart != -1 && jsonEnd != -1) {
                String jsonString = themeDescription.substring(jsonStart, jsonEnd + 1);
                String backgroundColor = extractColorFromJson(jsonString, "backgroundColor");
                String textColor = extractColorFromJson(jsonString, "textColor");
                
                if (backgroundColor != null && textColor != null) {
                    Theme theme = new Theme();
                    theme.setName("Custom Theme");
                    theme.setPrimaryColor(backgroundColor);
                    theme.setSecondaryColor(textColor);
                    theme.setIsDarkMode(isDarkColor(backgroundColor));
                    return theme;
                }
            }
        } catch (Exception e) {
            // Ignore parse errors, treat as custom description
        }
        
        // If not JSON, create a theme from the description
        Theme theme = new Theme();
        theme.setName(themeDescription);
        theme.setPrimaryColor("#FFFFFF");
        theme.setSecondaryColor("#000000");
        theme.setIsDarkMode(false);
        return theme;
    }
    
    /**
     * Extract color value from JSON string.
     */
    private String extractColorFromJson(String json, String key) {
        String pattern = "\"" + key + "\"\\s*:\\s*\"([^\"]+)\"";
        java.util.regex.Pattern p = java.util.regex.Pattern.compile(pattern);
        java.util.regex.Matcher m = p.matcher(json);
        
        if (m.find()) {
            return m.group(1);
        }
        return null;
    }
    
    /**
     * Check if a color is dark.
     */
    private boolean isDarkColor(String hexColor) {
        if (hexColor == null || !hexColor.startsWith("#")) {
            return false;
        }
        
        try {
            int color = android.graphics.Color.parseColor(hexColor);
            int r = android.graphics.Color.red(color);
            int g = android.graphics.Color.green(color);
            int b = android.graphics.Color.blue(color);
            // Calculate luminance
            double luminance = 0.299 * r + 0.587 * g + 0.114 * b;
            return luminance < 128;
        } catch (Exception e) {
            return false;
        }
    }

    /**
     * Select and apply a theme.
     *
     * @param themeId ID of the theme to select (1=Light, 2=Dark, 3=Blue)
     */
    public void selectTheme(Long themeId) {
        if (userId == null) {
            return;
        }
        
        User user = userRepository.getUserById(userId);
        if (user == null) {
            return;
        }
        
        // Determine theme name based on ID
        String themeName;
        if (themeId == 1) {
            themeName = "light";
        } else if (themeId == 2) {
            themeName = "dark";
        } else if (themeId == 3) {
            themeName = "blue";
        } else {
            themeName = "light"; // Default
        }
        
        // Update user's theme preference
        user.setThemePreference(themeName);
        userRepository.updateUser(user);
        
        // Load and apply the selected theme
        Theme selectedTheme = getThemeByName(themeName);
        if (selectedTheme != null) {
            currentTheme.setValue(selectedTheme);
        }
    }
    
    /**
     * Apply custom LLM-generated theme for the user.
     * 
     * This method loads the user's custom theme from their themePreference
     * and applies it to the app.
     * 
     * @return true if custom theme was found and applied, false otherwise
     */
    public boolean applyCustomTheme() {
        if (userId == null) {
            return false;
        }
        
        User user = userRepository.getUserById(userId);
        if (user == null || user.getThemePreference() == null) {
            return false;
        }
        
        String themePreference = user.getThemePreference();
        
        // Check if it's a predefined theme or LLM-generated
        if (isPredefinedTheme(themePreference)) {
            // Predefined theme - not a custom one
            return false;
        }
        
        // LLM-generated theme - parse and apply it
        Theme customTheme = parseLLMTheme(themePreference);
        if (customTheme != null) {
            currentTheme.setValue(customTheme);
            return true;
        }
        
        return false;
    }
    
    /**
     * Get a theme by its name.
     * 
     * @param themeName Name of the theme ("light", "dark", "blue")
     * @return Theme object or null if not found
     */
    private Theme getThemeByName(String themeName) {
        // NOTE: Hardcoded themes are disabled
        // All themes must be dynamically generated by LLM
        android.util.Log.w("ThemeViewModel", 
            "WARNING: Attempting to use hardcoded theme '" + themeName + "'." +
            "Themes must be dynamically generated by LLM. Returning placeholder theme to avoid crashes.");
        
        // Return placeholder theme to avoid crashes
        return createPlaceholderTheme(themeName);
    }
    
    /**
     * Create a placeholder theme to avoid crashes.
     * Uses cached LLM-generated theme if available, otherwise creates a fallback.
     * WARNING: This is only a placeholder theme to avoid crashes. Real themes should be dynamically generated by LLM.
     */
    private Theme createPlaceholderTheme(String themeName) {
        // Try to use cached LLM-generated default theme
        if (defaultThemeGenerator != null) {
            Theme defaultTheme = defaultThemeGenerator.getDefaultTheme(themeName);
            if (defaultTheme != null) {
                android.util.Log.d("ThemeViewModel", "Using cached LLM-generated default theme: " + themeName);
                return defaultTheme;
            }
        }
        
        // Last resort fallback (to avoid crash)
        Theme placeholder = new Theme();
        placeholder.setName(themeName != null ? themeName : "placeholder");
        placeholder.setPrimaryColor("#F5F5F5");
        placeholder.setSecondaryColor("#333333");
        placeholder.setIsDarkMode(false);
        android.util.Log.w("ThemeViewModel", "Using fallback theme for: " + themeName);
        return placeholder;
    }
    
