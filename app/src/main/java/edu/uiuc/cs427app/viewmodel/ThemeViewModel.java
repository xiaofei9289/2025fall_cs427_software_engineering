    /**
     * Load the current theme for the user.
     *
     * Called on app startup to restore user's theme preference.
     */
    private void loadCurrentTheme() {
        if (userId == null) {
            return;
        }
        
        User user = userRepository.getUserById(userId);
        if (user == null || user.getThemePreference() == null) {
            return;
        }
        
        String themePreference = user.getThemePreference();
        
        // Check if it's a predefined theme or LLM-generated
        if (isPredefinedTheme(themePreference)) {
            // Predefined theme
            Theme theme = getThemeByName(themePreference);
            currentTheme.setValue(theme);
        } else {
            // LLM-generated theme
            Theme customTheme = parseLLMTheme(themePreference);
            if (customTheme != null) {
                currentTheme.setValue(customTheme);
            }
        }
    }
    
    /**
     * Get the current active theme (for quick access).
     * 
     * @return Current theme or default theme
     */
    public Theme getCurrentActiveTheme() {
        Theme theme = currentTheme.getValue();
        if (theme != null) {
            return theme;
        }
        
        // Try to use cached default theme
        if (defaultThemeGenerator != null) {
            Theme defaultTheme = defaultThemeGenerator.getDefaultTheme("light");
            if (defaultTheme != null) {
                return defaultTheme;
            }
        }
        
        // Last resort fallback
        Theme fallback = new Theme();
        fallback.setName("fallback");
        fallback.setPrimaryColor("#F5F5F5");
        fallback.setSecondaryColor("#333333");
        fallback.setIsDarkMode(false);
        return fallback;
    }
